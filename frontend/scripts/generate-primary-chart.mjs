import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const asset = new URL('../public/dashboard/primary_teeth.svg', import.meta.url);
const output = new URL('../src/app/clinic-selection/[code]/appointments/primaryChartData.ts', import.meta.url);
const svg = readFileSync(asset, 'utf8');
const paths = [...svg.matchAll(/<path\b[^>]*\bd="([^"]*)"[^>]*\/>/g)].map((match) => match[1]);

// The first path contains the upper arch's outline followed by ten tooth
// interiors. The lower arch is split across five compound paths in this asset.
const interiors = (index) => paths[index].match(/M[^M]+/g).slice(1);

// All coordinates in this supplied SVG are absolute. Include Bezier control
// points to get a stable horizontal ordering of the tooth interiors.
function centerX(d) {
  const xs = [];
  for (const [, command, args] of d.matchAll(/([MLCHVZ])([^MLCHVZ]*)/g)) {
    const values = args.match(/-?\d*\.?\d+/g)?.map(Number) ?? [];
    if (command === 'H') xs.push(...values);
    else if (command !== 'V') {
      for (let i = 0; i < values.length; i += 2) xs.push(values[i]);
    }
  }
  return (Math.min(...xs) + Math.max(...xs)) / 2;
}

const upper = interiors(0).sort((a, b) => centerX(a) - centerX(b));
const lower = [1, 2, 3, 4, 8].flatMap(interiors).sort((a, b) => centerX(a) - centerX(b));
assert.equal(upper.length, 10);
assert.equal(lower.length, 10);
const upperNumbers = ['55', '54', '53', '52', '51', '61', '62', '63', '64', '65'];
const lowerNumbers = ['85', '84', '83', '82', '81', '71', '72', '73', '74', '75'];
const teeth = [...upper, ...lower].map((d, index) => ({
  n: [...upperNumbers, ...lowerNumbers][index],
  d,
}));
assert.equal(new Set(teeth.map(({ n }) => n)).size, 20);
assert(teeth.every(({ d }) => d.endsWith('Z')));
writeFileSync(output, [
  '// Generated by scripts/generate-primary-chart.mjs from public/dashboard/primary_teeth.svg.',
  '// Primary FDI numbers use quadrants 5–8, positions 1–5.',
  'export const PRIMARY_VIEWBOX = "0 0 2410 2911";',
  'export const PRIMARY_TEETH: ReadonlyArray<{ n: string; d: string }> = [',
  ...teeth.map((tooth) => `  ${JSON.stringify(tooth)},`),
  '];',
  '',
].join('\n'));
console.log(`Generated ${teeth.length} primary tooth targets: ${fileURLToPath(output)}`);
